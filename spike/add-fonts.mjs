// Installs every font in fonts.json from npm (@fontsource, OFL), copies Devanagari + Latin woff2 into public/fonts,
// and writes public/fonts.css. Latin is bundled on purpose: without it digits, "." and English words fall back to
// whatever the machine has, and canvas vs DOM measure that fallback differently (Phase 0 finding).
// Usage: node add-fonts.mjs            (all fonts in fonts.json)
//        node add-fonts.mjs Halant Hind (only these, by name)
import fs from 'node:fs'
import path from 'node:path'
import { execSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const root = path.dirname(fileURLToPath(import.meta.url))
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'fonts.json'), 'utf8')).fonts
const only = process.argv.slice(2)
const list = only.length ? cfg.filter(f => only.includes(f.name)) : cfg
if (!list.length) { console.error('No matching fonts in fonts.json'); process.exit(1) }

const pub = path.join(root, 'public'), out = path.join(pub, 'fonts'), lic = path.join(out, 'licenses')
fs.mkdirSync(lic, { recursive: true })

const missing = list.filter(f => !fs.existsSync(path.join(root, 'node_modules/@fontsource', f.pkg)))
if (missing.length) {
  console.log(`Installing ${missing.length} font packages from npm (one-time, a few MB each)...`)
  const run = pkgs => execSync(`npm install --no-audit --no-fund --save-dev ${pkgs.map(p => '@fontsource/' + p).join(' ')}`, { cwd: root, stdio: 'ignore' })
  try { run(list.map(f => f.pkg)) }
  catch { for (const f of list) { try { run([f.pkg]) } catch { console.warn(`  ! could not install @fontsource/${f.pkg}`) } } }
}

let css = '/* generated by add-fonts.mjs - do not edit */\n'
const rows = []
for (const f of list) {
  const dir = path.join(root, 'node_modules/@fontsource', f.pkg)
  if (!fs.existsSync(dir)) { rows.push([f.name, 'NOT INSTALLED', '', '']); continue }
  const got = { devanagari: [], latin: [] }
  for (const w of [400, 700]) {
    const file = path.join(dir, `${w}.css`)
    if (!fs.existsSync(file)) continue
    for (const block of fs.readFileSync(file, 'utf8').match(/@font-face\s*\{[^}]*\}/g) || []) {
      const m = block.match(/files\/([^)]*?-(devanagari|latin)-\d+-normal\.woff2)/)
      if (!m) continue                                   // skips latin-ext, vietnamese, etc.
      fs.copyFileSync(path.join(dir, 'files', m[1]), path.join(out, m[1]))
      got[m[2]].push(w)
      css += block
        .replace(/font-family:\s*'[^']*'/, `font-family: '${f.name}'`)
        .replace(/src:[^;]*;/, `src: url(fonts/${m[1]}) format('woff2');`) + '\n'
    }
  }
  const l = path.join(dir, 'LICENSE'); if (fs.existsSync(l)) fs.copyFileSync(l, path.join(lic, `${f.pkg}.txt`))
  rows.push([f.name, got.devanagari.join('/') || 'MISSING', got.latin.join('/') || 'MISSING', f.role])
}
// merge with previous fonts.css so adding one font does not drop the others
const prev = path.join(pub, 'fonts.css')
if (only.length && fs.existsSync(prev)) {
  const keep = fs.readFileSync(prev, 'utf8').match(/@font-face\s*\{[^}]*\}/g) || []
  const names = new Set(list.map(f => f.name))
  css += keep.filter(b => !names.has((b.match(/font-family:\s*'([^']*)'/) || [])[1])).join('\n') + '\n'
}
fs.writeFileSync(prev, css)
console.log('font'.padEnd(26), 'devanagari'.padEnd(12), 'latin'.padEnd(10), 'role')
for (const r of rows) console.log(r[0].padEnd(26), r[1].padEnd(12), r[2].padEnd(10), r[3])
console.log('\nWrote public/fonts.css. Now: node run.mjs            (launch fonts)\n                         node run.mjs --all      (every font in fonts.json)\n                         node run.mjs --fonts "Halant,Hind"')
